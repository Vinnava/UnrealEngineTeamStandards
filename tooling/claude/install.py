#!/usr/bin/env python3
"""Installs the team standard's Claude kit into a project's .claude/ folder (27.7).

From the project root, with the standard pinned at standards/ (26.4):

    python standards/tooling/claude/install.py [--replicates] [--editor-mcp]   install, or refresh
    python standards/tooling/claude/install.py --check                         CI: fail if .claude/ is stale or edited

--replicates loads section 11 with the C++ rules; --editor-mcp enables Epic's plugin for the editor
connection (27.8). A refresh remembers both; --no-replicates and --no-editor-mcp turn them off.

It generates what Claude Code must find inside .claude/ - path-scoped rule files, agents and skills -
from the pinned copy, and merges the kit's keys into .claude/settings.json without touching the rest.
Hooks, scripts and the status line are not copied: settings point at them inside standards/, so
verify-standard.py proves them unedited. .claude/ue-kit.json records what was generated, so a
re-install removes files an older kit made, and --check catches a hand edit.

Standard library only. Never edit a generated file - change the standard, or record an override.
"""

import argparse
import hashlib
import json
import os
import re
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent
STANDARDS = KIT.parents[1]
MARKER = "ue-kit.json"
KIT_HOOK_MARK = "tooling/claude/hooks/"
# Epic's Claude Code plugin for the Unreal MCP editor connection (27.8), from Anthropic's official marketplace
EDITOR_MCP_PLUGIN = "unreal-engine-skills-for-claude-code@claude-plugins-official"
INCLUDE = re.compile(r"^\{\{INCLUDE (?P<path>[\w./-]+)\}\}$", re.M)
FRONTMATTER = re.compile(r"\A---\n.*?\n---\n", re.S)


def standard_version() -> str:
    match = re.search(r"\*\*Version (\d+\.\d+\.\d+)\*\*", (STANDARDS / "README.md").read_text(encoding="utf-8"))
    return match.group(1) if match else "unknown"


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def render(text: str, values: dict[str, str]) -> str:
    """Fills {{STANDARDS}} and {{PYTHON}}, and replaces each {{INCLUDE rules/x.md}} line with that file."""
    text = INCLUDE.sub(lambda match: read(STANDARDS / match.group("path")).rstrip("\n"), text)
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    return text


def stamp(text: str, source: str, values: dict[str, str]) -> str:
    """Adds the generated-file notice after any frontmatter - which must stay on the first line."""
    notice = (f"<!-- Generated by {values['STANDARDS']}/tooling/claude/install.py from {values['STANDARDS']}/{source}, "
              f"standard {values['VERSION']}. Do not edit: change the standard or re-run the installer (27.7). -->\n\n")
    front = FRONTMATTER.match(text)
    if front:
        return text[:front.end()] + notice + text[front.end():].lstrip("\n")
    return notice + text


def planned_files(values: dict[str, str], replicates: bool) -> dict[str, str]:
    """Relative path under .claude/ -> content, for every file the kit generates."""
    files = {}
    groups = json.loads(read(KIT / "rule-groups.json"))["groups"]
    for group in groups:
        if group.get("only_if") == "replicates" and not replicates:
            continue
        paths = "".join(f'  - "{pattern}"\n' for pattern in group["paths"])
        for rule in group["rules"]:
            body = read(STANDARDS / "rules" / f"{rule}.md")
            files[f"rules/standard/{rule}.md"] = stamp(f"---\npaths:\n{paths}---\n\n{body}", f"rules/{rule}.md", values)
    for agent in sorted((KIT / "agents").glob("*.md")):
        files[f"agents/{agent.name}"] = stamp(render(read(agent), values), f"tooling/claude/agents/{agent.name}", values)
    for skill in sorted((KIT / "skills").glob("*/SKILL.md")):
        source = f"tooling/claude/skills/{skill.parent.name}/SKILL.md"
        files[f"skills/{skill.parent.name}/SKILL.md"] = stamp(render(read(skill), values), source, values)
    return files


def is_kit_hook_group(group: dict) -> bool:
    for hook in group.get("hooks", []):
        text = " ".join([hook.get("command", "")] + list(hook.get("args", []))).replace("\\", "/")
        if KIT_HOOK_MARK in text:
            return True
    return False


def merge_settings(existing: dict, kit: dict, previous_allow: list[str], previous_plugins: list[str]) -> dict:
    """The project's settings with the kit's keys applied. Everything the kit does not own is kept."""
    merged = json.loads(json.dumps(existing))
    for key in ("model", "plansDirectory", "statusLine"):
        merged[key] = kit[key]
    plugins = merged.setdefault("enabledPlugins", {})
    for name in previous_plugins:
        if name not in kit["enabledPlugins"]:
            plugins.pop(name, None)
    plugins.update(kit["enabledPlugins"])
    model_settings = merged.setdefault("modelSettings", {})
    for model, config in kit["modelSettings"].items():
        model_settings[model] = {**model_settings.get(model, {}), **config}
    permissions = merged.setdefault("permissions", {})
    allow = [rule for rule in permissions.get("allow", []) if rule not in previous_allow]
    permissions["allow"] = allow + [rule for rule in kit["permissions"]["allow"] if rule not in allow]
    hooks = merged.setdefault("hooks", {})
    for event in list(hooks):
        hooks[event] = [group for group in hooks[event] if not is_kit_hook_group(group)]
        if not hooks[event]:
            del hooks[event]
    for event, groups in kit["hooks"].items():
        hooks.setdefault(event, []).extend(groups)
    return merged


def find_project(explicit: Path | None) -> Path | None:
    if explicit:
        return explicit.resolve()
    for origin in (STANDARDS.parent, Path.cwd()):
        for candidate in (origin, *origin.parents):
            if any(candidate.glob("*.uproject")):
                return candidate
    return None


def load_json(path: Path) -> dict:
    try:
        return json.loads(read(path))
    except (OSError, ValueError):
        return {}


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def main() -> int:
    parser = argparse.ArgumentParser(description="Install the team standard's Claude kit into a project.")
    parser.add_argument("--project", type=Path, help="the project root; found from the standard's location if omitted")
    parser.add_argument("--replicates", action=argparse.BooleanOptionalAction, default=None,
                        help="the project replicates: load section 11 with the C++ rules")
    parser.add_argument("--editor-mcp", action=argparse.BooleanOptionalAction, default=None,
                        help="enable Epic's plugin for the Unreal MCP editor connection (27.8)")
    parser.add_argument("--python", help="the command hooks and scripts run with; 'python' on Windows, else 'python3'")
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 if .claude/ differs from the kit")
    parser.add_argument("--force", action="store_true", help="install into a folder with no .uproject")
    args = parser.parse_args()

    project = find_project(args.project)
    if project is None or (not any(project.glob("*.uproject")) and not args.force):
        print("No .uproject found - run from the project root, pass --project, or --force.")
        return 2
    claude = project / ".claude"
    marker = load_json(claude / MARKER)

    # Sticky: a refresh keeps the choices an earlier install recorded, until a --no- flag turns one off
    replicates = args.replicates if args.replicates is not None else marker.get("replicates", False)
    editor_mcp = args.editor_mcp if args.editor_mcp is not None else marker.get("editor_mcp", False)
    python = args.python or marker.get("python") or ("python" if sys.platform == "win32" else "python3")
    standards_rel = os.path.relpath(STANDARDS, project).replace("\\", "/")
    values = {"STANDARDS": standards_rel, "PYTHON": python, "VERSION": standard_version()}

    files = planned_files(values, replicates)
    kit_settings = json.loads(render(read(KIT / "settings.json"), values))
    if editor_mcp:
        kit_settings["enabledPlugins"][EDITOR_MCP_PLUGIN] = True
    existing = load_json(claude / "settings.json")
    merged = merge_settings(existing, kit_settings, marker.get("allow", []), marker.get("plugins", []))
    previous = marker.get("files", {})
    stale = sorted(set(previous) - set(files))

    if args.check:
        problems = []
        for relative, text in files.items():
            path = claude / relative
            if not path.is_file():
                problems.append(f"{relative}: missing")
            elif read(path) != text:
                problems.append(f"{relative}: differs from the kit - edited by hand, or the standard moved on")
        problems += [f"{relative}: left over from an older kit" for relative in stale if (claude / relative).is_file()]
        if merged != existing:
            problems.append("settings.json: the kit's keys are missing or changed")
        for problem in problems:
            print(f"error: {problem}")
        print(f"\nClaude kit {values['VERSION']}: {len(files)} files checked, {len(problems)} problems"
              + (" - run install.py to fix" if problems else ""))
        return 1 if problems else 0

    for relative, text in files.items():
        write(claude / relative, text)
    for relative in stale:
        path = claude / relative
        if path.is_file() and digest(read(path)) == previous[relative]:
            path.unlink()
        elif path.is_file():
            print(f"warning: kept {relative} - an older kit made it, but it was edited since")
    write(claude / "settings.json", json.dumps(merged, indent=2) + "\n")
    write(claude / MARKER, json.dumps({
        "standard_version": values["VERSION"], "standards": standards_rel, "python": python,
        "replicates": replicates, "editor_mcp": editor_mcp, "allow": kit_settings["permissions"]["allow"],
        "plugins": sorted(kit_settings["enabledPlugins"]),
        "files": {relative: digest(text) for relative, text in sorted(files.items())},
    }, indent=2) + "\n")

    counts = {kind: sum(1 for relative in files if relative.startswith(kind)) for kind in ("rules", "agents", "skills")}
    print(f"Installed Claude kit {values['VERSION']} into {claude}: {counts['rules']} rule files, "
          f"{counts['agents']} agents, {counts['skills']} skills, settings merged"
          + (f", {len(stale)} old files handled" if stale else ""))
    print("Next: CLAUDE.md from standards/tooling/project-template/ if the project has none; the clangd binary "
          "and a compile database on each machine (27.4); 'install.py --check' in the every-commit CI tier"
          + ("; and the editor steps in 27.8 for the editor connection." if editor_mcp else "."))
    if not (project / ".clangd").is_file():
        print(f"warning: no .clangd at the project root - copy {standards_rel}/tooling/.clangd there, or clangd "
              f"reports false errors in every Unreal source file (27.4)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
